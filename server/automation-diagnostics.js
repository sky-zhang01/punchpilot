const AUTOMATION_FAILURE_STAGES = new Set([
  'account_queue',
  'authorization',
  'browser_init',
  'calendar_guard',
  'cleanup',
  'company_binding',
  'credentials',
  'employee_identity',
  'identity_binding',
  'login',
  'mutation',
  'operation',
  'queue',
  'state_read',
  'work_record_guard',
]);

export function normalizeAutomationFailureStage(stage, fallback = null) {
  if (AUTOMATION_FAILURE_STAGES.has(stage)) return stage;
  return AUTOMATION_FAILURE_STAGES.has(fallback) ? fallback : null;
}

export function normalizeAutomationErrorCode(code) {
  return AUTOMATION_ERROR_CODES.has(code) ? code : null;
}

export function annotateAutomationFailureStage(error, stage) {
  if (!error || typeof error !== 'object') return error;
  if (AUTOMATION_FAILURE_STAGES.has(error.automationStage)) return error;
  try {
    error.automationStage = normalizeAutomationFailureStage(stage, 'operation');
  } catch {}
  return error;
}

export function automationFailureStage(error, fallback = 'operation') {
  return normalizeAutomationFailureStage(error?.automationStage, fallback);
}
